/**
 * Enterprise Trade Isolation Engine:
 * Returns pure, trade-isolated work orders with zero trade cross-contamination.
 */
export const getOrdersForTrade = (tradeCategoryOrTitle: string = ''): UniversalWorkOrder[] => {
  const norm = tradeCategoryOrTitle.toLowerCase().trim();
  if (/ac\b|cool|hvac|chiller|refrig|vent|compressor/i.test(norm)) {
    return HVAC_WORK_ORDERS;
  }
  if (/beauty|makeup|salon|bridal|hair|spa|facial|cosmetic|draping/i.test(norm)) {
    return MAKEUP_WORK_ORDERS;
  }
  if (/plumb|pipe|drain|leak|water|pump|sewer|faucet/i.test(norm)) {
    return PLUMBING_WORK_ORDERS;
  }
  if (/carpent|wood|furnit|door|ply|cabinet|timber/i.test(norm)) {
    return CARPENTRY_WORK_ORDERS;
  }
  // Default to electrical
  return ELECTRICAL_WORK_ORDERS;
};

